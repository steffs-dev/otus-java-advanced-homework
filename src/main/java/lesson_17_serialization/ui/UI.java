package lesson_17_serialization.ui;

/**
 * Интерфейс пользовательского ввода-вывода.
 *
 * <p>Позволяет абстрагироваться от конкретного источника ввода и вывода.
 * Например, вместо консоли можно реализовать графический интерфейс</p>
 */

public interface UI {

    /**
     * Выводит строку с переносом на новую строку.
     *
     * @param message сообщение для вывода
     */

    void print(String message);

    /**
     * Выводит отформатированную строку.
     *
     * <p>Форматирование соответствует синтаксису {@link java.util.Formatter}.</p>
     *
     * @param message шаблон сообщения
     * @param args    аргументы для подстановки в шаблон
     */

    void printf(String message, Object... args);

    /**
     * Читает одну строку из пользовательского ввода.
     *
     * @return введенная строка
     */

    String readLine();

    /**
     * Освобождает ресурсы, связанные с вводом.
     */

    void close();
}
